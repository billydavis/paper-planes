# PlatformIO pre-build hook. Runs the system Python (which has Pillow,
# certifi, cryptography), not PlatformIO's own environment.
#
# 1. Regenerates src/generated/ when an output is missing or older than what
#    it's made from:
#      tools/fontgen.py -> fonts_gen.h
#      tools/logogen.py -> logos_gen.h (downloads logos it lacks)
#      tools/datagen.py -> airports.bin, airlines_gen.h, certs_gen.h
#                          (from ../flight-tracker, or FLIGHT_TRACKER_DIR)
#      tools/webgen.py  -> web_assets_gen.h (from web/)
# 2. Writes src/generated/version_gen.h (git describe), only when it changes.
# 3. On the board: flashes airports.bin into its partition along with the
#    firmware on `pio run -t upload` (set SKIP_AIRPORTS=1 to leave it), and
#    adds `pio run -t uploadairports` to write just the data.
import glob
import os
import shutil
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

root = env["PROJECT_DIR"]  # noqa: F821
gen_dir = os.path.join(root, "src", "generated")
py = shutil.which("python") or shutil.which("python3") or "python"
ft = os.environ.get("FLIGHT_TRACKER_DIR") or os.path.join(root, "..", "flight-tracker")


def mtime(p):
    return os.path.getmtime(p) if os.path.exists(p) else 0


jobs = (
    ("fontgen.py", ["fonts_gen.h"], []),
    ("logogen.py", ["logos_gen.h"], []),
    ("datagen.py", ["airports.bin", "airlines_gen.h", "certs_gen.h"],
     [os.path.join(ft, "data", "airports.csv"),
      os.path.join(ft, "src", "web", "assets", "js", "airlines.js"),
      os.path.join(ft, "src", "server", "epaper.py"),
      os.path.join(root, "tools", "extra_roots.pem")]),
    ("webgen.py", ["web_assets_gen.h"], glob.glob(os.path.join(root, "web", "*"))),
)
for script, outputs, sources in jobs:
    gen = os.path.join(root, "tools", script)
    newest = max([mtime(gen)] + [mtime(s) for s in sources])
    outs = [os.path.join(gen_dir, o) for o in outputs]
    if any(not os.path.exists(o) or mtime(o) < newest for o in outs):
        subprocess.check_call([py, gen])

# Firmware version: shown on the web page and in the boot log.
try:
    version = subprocess.check_output(["git", "describe", "--always", "--dirty", "--tags"], cwd=root,
                                      text=True, stderr=subprocess.DEVNULL).strip()
except (OSError, subprocess.CalledProcessError):
    version = "unknown"
header = f'#pragma once\n// Generated by tools/pio_generate.py. Do not edit.\n#define FW_VERSION "{version}"\n'
version_h = os.path.join(gen_dir, "version_gen.h")
if not os.path.exists(version_h) or open(version_h).read() != header:
    os.makedirs(gen_dir, exist_ok=True)
    with open(version_h, "w", newline="\n") as f:
        f.write(header)

# Airport data partition (board builds only).
if env.get("PIOPLATFORM") == "espressif32":  # noqa: F821
    offset = None
    with open(os.path.join(root, "partitions.csv")) as f:
        for line in f:
            cols = [c.strip() for c in line.split(",")]
            if cols and cols[0] == "airports":
                offset = cols[3]
    image = os.path.join(gen_dir, "airports.bin")
    if offset and not os.environ.get("SKIP_AIRPORTS"):
        env.Append(FLASH_EXTRA_IMAGES=[(offset, image)])  # noqa: F821
    if offset:
        env.AddCustomTarget(  # noqa: F821
            name="uploadairports",
            dependencies=None,
            actions=[f'"$PYTHONEXE" "$UPLOADER" --chip esp32s3 --port "$UPLOAD_PORT" --baud $UPLOAD_SPEED '
                     f'write_flash {offset} "{image}"'],
            title="Upload airport data",
            description="Write src/generated/airports.bin to the airports partition over USB",
        )

# Host tests: link the C++ runtime in, so the test binary doesn't pick up
# whichever libstdc++ DLL happens to be first on PATH.
if env.get("PIOPLATFORM") == "native":  # noqa: F821
    env.Append(LINKFLAGS=["-static"])  # noqa: F821
