"""Pack the web pages in web/ into the firmware, gzipped.

    python tools/webgen.py

Writes src/generated/web_assets_gen.h: one WebAsset per file, served by
src/web/server.cpp with Content-Encoding: gzip. Edit the files in web/ as
ordinary HTML/CSS; the build reruns this when they change.

URL for each file: index.html -> "/", other .html -> "/<name>", anything
else -> "/<file name>".
"""
import gzip
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "generated", "web_assets_gen.h")
MIME = {".html": "text/html", ".css": "text/css", ".js": "application/javascript", ".svg": "image/svg+xml"}


def url_for(name):
    base, ext = os.path.splitext(name)
    if name == "index.html":
        return "/"
    return "/" + base if ext == ".html" else "/" + name


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    files = sorted(f for f in os.listdir(WEB) if os.path.splitext(f)[1] in MIME)
    lines = ["// Generated by tools/webgen.py from web/. Do not edit.", "#pragma once", "#include <stdint.h>", "",
             "struct WebAsset {", "  const char *path, *mime;", "  const uint8_t *gz;", "  uint32_t len;", "};", ""]
    total = raw_total = 0
    for i, name in enumerate(files):
        with open(os.path.join(WEB, name), "rb") as f:
            raw = f.read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)   # mtime=0: same input, same bytes
        total += len(gz)
        raw_total += len(raw)
        lines.append(f"static const uint8_t WEB_{i}[] = {{  // {name}")
        for j in range(0, len(gz), 32):
            lines.append(",".join(str(b) for b in gz[j:j + 32]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    for i, name in enumerate(files):
        mime = MIME[os.path.splitext(name)[1]] + ("; charset=utf-8" if name.endswith((".html", ".css", ".js")) else "")
        lines.append(f'  {{"{url_for(name)}", "{mime}", WEB_{i}, sizeof(WEB_{i})}},')
    lines.append("};")
    lines.append("static const int WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"webgen: {len(files)} files, {raw_total // 1024} KB -> {total // 1024} KB gzipped")


if __name__ == "__main__":
    main()
