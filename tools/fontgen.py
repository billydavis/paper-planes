"""Turn the mockup's TrueType fonts into 1-bit bitmap fonts for the firmware.

    python tools/fontgen.py        -> writes src/generated/fonts_gen.h

Rendered with the same Pillow calls as tools/mockup.py, so text on the panel
matches the mockups pixel for pixel (give or take sub-pixel rounding).

The output is generated from fonts installed on this PC (Bahnschrift and
Consolas ship with Windows), so it is not committed; PlatformIO runs this
script before each build when the header is missing or stale
(tools/pio_generate.py).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "generated", "fonts_gen.h")
WIN = "C:/Windows/Fonts/"

# role name -> (file, size, variable-font weight or None)
FONTS = {
    "airline":  ("bahnschrift.ttf", 28, "Bold"),
    "flight":   ("consolab.ttf",    32, None),
    "route":    ("bahnschrift.ttf", 84, "Bold"),
    "city":     ("bahnschrift.ttf", 18, "Regular"),
    "aircraft": ("bahnschrift.ttf", 22, "SemiBold"),
    "label":    ("bahnschrift.ttf", 13, "Bold"),
    "value":    ("consolab.ttf",    30, None),
    "unit":     ("bahnschrift.ttf", 16, "SemiBold"),
    "caption":  ("bahnschrift.ttf", 12, "Bold"),
    "note":     ("bahnschrift.ttf", 15, "Bold"),
    "big":      ("bahnschrift.ttf", 56, "Bold"),
}

# Printable ASCII, then a few extras the UI uses. The firmware maps UTF-8
# codepoints onto this list (see font.cpp).
EXTRAS = [0xB0, 0xB7, 0x2014]          # degree sign, middle dot, em dash
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in EXTRAS]


def load(file, size, weight):
    f = ImageFont.truetype(WIN + file, size)
    if weight:
        f.set_variation_by_name(weight)
    return f


def glyph(font, ch):
    """(bits, w, h, x0, y0, advance_in_64ths) for one character. x0/y0 are
    relative to the pen position and the top of the line (Pillow's 'la'
    anchor), which is what ImageDraw.text((x, y)) uses."""
    x0, y0, x1, y1 = font.getbbox(ch)
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    adv = round(font.getlength(ch) * 64)
    if w == 0 or h == 0:
        return b"", 0, 0, 0, 0, adv
    img = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((-x0, -y0), ch, font=font, fill=1)
    px = img.load()
    bits, acc, n = bytearray(), 0, 0
    for y in range(h):
        for x in range(w):
            acc = (acc << 1) | (1 if px[x, y] else 0)
            n += 1
            if n == 8:
                bits.append(acc); acc = n = 0
    if n:
        bits.append(acc << (8 - n))
    return bytes(bits), w, h, x0, y0, adv


def main():
    lines = [
        "// Generated by tools/fontgen.py - do not edit.",
        "#pragma once",
        '#include "ui/font.h"',
        "",
    ]
    total = 0
    for name, (file, size, weight) in FONTS.items():
        font = load(file, size, weight)
        asc, desc = font.getmetrics()
        data, glyphs = bytearray(), []
        for ch in CHARS:
            bits, w, h, x0, y0, adv = glyph(font, ch)
            glyphs.append((len(data), w, h, x0, y0, adv))
            data += bits
        total += len(data) + 10 * len(glyphs)
        lines.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const Glyph {name}_glyphs[] = {{")
        for g in glyphs:
            lines.append("  {%d,%d,%d,%d,%d,%d}," % g)
        lines.append("};")
        lines.append(f"static const Font FONT_{name.upper()} = "
                     f"{{{name}_bits, {name}_glyphs, {asc}, {desc}}};")
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"fontgen: {len(FONTS)} fonts, {total / 1024:.0f} KB -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
